#!/usr/bin/env python3
"""Print abseil's installed static archives in link order, dependents first.

Reads the CMake export files abseil installs (<cmake-dir>/abslTargets.cmake and
abslTargets-<config>.cmake), follows INTERFACE_LINK_LIBRARIES between absl::
targets, and prints one absolute archive path per line such that every archive
precedes every archive it depends on. A single pass over the list therefore
resolves all intra-abseil references without --start-group. Archives present in
<lib-dir> but not described by the export files are appended at the end with a
warning on stderr.

Usage: python3 -I absl_link_order.py <cmake-dir> <lib-dir>
Run with -I: the export files are generated by a downloaded build.
"""

